import XCTest
@testable import PacBag

/// All six export generators against golden files, with the footer date stripped.
/// Pinned bug: a sub-bag's items count in the totals but aren't listed. The export fix commit
/// flips that, and it's reviewed as a diff of these goldens.
///
/// To rewrite them on purpose: `TEST_RUNNER_RECORD_GOLDENS=1 xcodebuild test ...`, then read the diff.
@MainActor
final class ExportGoldenTests: XCTestCase {
    private var coreData: CoreDataManager!
    private var trip: Trip!
    private var bag: Bag!

    override func setUp() async throws {
        coreData = CoreDataManager(inMemory: true)
        let make = ModelFactory(context: coreData.context)

        // Local dates, so the printed range doesn't depend on the machine's time zone.
        let calendar = Calendar.current
        trip = make.trip("Golden Trip", destination: "Lisbon")
        trip.startDate = try XCTUnwrap(calendar.date(from: DateComponents(year: 2027, month: 6, day: 1, hour: 12)))
        trip.endDate = try XCTUnwrap(calendar.date(from: DateComponents(year: 2027, month: 6, day: 8, hour: 12)))
        trip.tripDescription = "Work and a weekend"

        bag = make.bag("Cabin Case", in: trip, bagWeight: 3, maxWeight: 10)
        make.item("Charger", in: bag, weight: 0.25, isPacked: true, category: "Electronics")
        make.item("Loose Thing", in: bag, weight: 1)
        make.item("Socks", in: bag, weight: 0.05, quantity: 2, category: "Clothes", description: "the thick ones")

        let sub = make.bag("Wash Bag", parent: bag, bagWeight: 0.5, maxWeight: 2)
        make.item("Hidden In Sub Bag", in: sub, weight: 0.5, isPacked: true, category: "Toiletries")

        _ = make.bag("Empty Tote", in: trip, bagWeight: 0.5, maxWeight: 5)
    }

    func testTripPlainText() throws {
        try assertGolden(SharingManager.shared.exportTrip(trip, format: .plainText).content, "export_trip_plainText")
    }

    func testTripMarkdown() throws {
        try assertGolden(SharingManager.shared.exportTrip(trip, format: .markdown).content, "export_trip_markdown")
    }

    func testTripRichText() throws {
        try assertGolden(SharingManager.shared.exportTrip(trip, format: .richText).content, "export_trip_richText")
    }

    func testBagPlainText() throws {
        try assertGolden(SharingManager.shared.exportBag(bag, format: .plainText).content, "export_bag_plainText")
    }

    func testBagMarkdown() throws {
        try assertGolden(SharingManager.shared.exportBag(bag, format: .markdown).content, "export_bag_markdown")
    }

    func testBagRichText() throws {
        try assertGolden(SharingManager.shared.exportBag(bag, format: .richText).content, "export_bag_richText")
    }

    func testSubBagItemsAreCountedButNotListed() {
        let content = SharingManager.shared.exportBag(bag, format: .plainText).content

        XCTAssertFalse(content.contains("Hidden In Sub Bag"))
        XCTAssertTrue(content.contains("Items: 2/4 packed"))
    }

    /// "Generated by PacBag on Nov 1, 2026 at 9:41 PM" keeps its wrapping and loses the date.
    private func stripFooterDate(_ content: String) -> String {
        content.replacingOccurrences(of: #"(Generated by PacBag on )[^*\\\n]*"#, with: "$1<date>", options: .regularExpression)
    }

    private func assertGolden(_ content: String, _ name: String, filePath: String = #filePath, line: UInt = #line) throws {
        let actual = stripFooterDate(content)
        if ProcessInfo.processInfo.environment["RECORD_GOLDENS"] == "1" {
            let folder = URL(fileURLWithPath: filePath).deletingLastPathComponent().deletingLastPathComponent()
                .appendingPathComponent("Fixtures/exports")
            try actual.write(to: folder.appendingPathComponent("\(name).golden"), atomically: true, encoding: .utf8)
            return
        }
        let url = try XCTUnwrap(Bundle(for: Self.self).url(forResource: name, withExtension: "golden"), "\(name).golden isn't in the test bundle", line: line)
        XCTAssertEqual(actual, try String(contentsOf: url, encoding: .utf8), line: line)
    }
}
